#ifndef G45_PROTOCOL_H
#define G45_PROTOCOL_H
#define G45_ABI 1u
#define G45_MAGIC 0x314f52463534474fULL
#define G45_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G45_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G45_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G45_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G45_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G45_STATUS;
typedef struct {G45_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G45_REGISTER_COUNT];} G45_SNAPSHOT;
typedef struct {
 G45_STATUS Status;G45_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G45_PMIC;
typedef struct {
 G45_STATUS Status;G45_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G45_TRIAL;
C_ASSERT(sizeof(G45_REQUEST)==16);
C_ASSERT(sizeof(G45_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G45_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G45_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G45_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G45_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G45_PMIC)==1728);
C_ASSERT(sizeof(G45_RSC_RESULT)==3264);
C_ASSERT(sizeof(G45_POWER_RESULT)==34392);
C_ASSERT(sizeof(G45_TOUCH_RESULT)==14292);
C_ASSERT(sizeof(G45_TRIAL_RESULT)==55760);
C_ASSERT(FIELD_OFFSET(G45_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G45_TRIAL,ElapsedTicks)==55848);
C_ASSERT(sizeof(G45_TRIAL)==55864);
#endif
