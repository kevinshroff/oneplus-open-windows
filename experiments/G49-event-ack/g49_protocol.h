#ifndef G49_PROTOCOL_H
#define G49_PROTOCOL_H
#define G49_ABI 1u
#define G49_MAGIC 0x314f52463934474fULL
#define G49_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G49_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G49_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G49_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G49_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G49_STATUS;
typedef struct {G49_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G49_REGISTER_COUNT];} G49_SNAPSHOT;
typedef struct {
 G49_STATUS Status;G49_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G49_PMIC;
typedef struct {
 G49_STATUS Status;G49_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G49_TRIAL;
C_ASSERT(sizeof(G49_REQUEST)==16);
C_ASSERT(sizeof(G49_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G49_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G49_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G49_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G49_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G49_PMIC)==1728);
C_ASSERT(sizeof(G49_RSC_RESULT)==3264);
C_ASSERT(sizeof(G49_POWER_RESULT)==34392);
C_ASSERT(sizeof(G49_TOUCH_RESULT)==27476);
C_ASSERT(sizeof(G49_TRIAL_RESULT)==68944);
C_ASSERT(FIELD_OFFSET(G49_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G49_TRIAL,ElapsedTicks)==69032);
C_ASSERT(sizeof(G49_TRIAL)==69048);
#endif

C_ASSERT(FIELD_OFFSET(G49_TOUCH_RESULT,Ack)==27168);
C_ASSERT(FIELD_OFFSET(G49_TOUCH_RESULT,Post)==27312);
C_ASSERT(FIELD_OFFSET(G49_TOUCH_RESULT,IrqSamples)==27456);
C_ASSERT(FIELD_OFFSET(G49_TOUCH_RESULT,ReportIrq)==27460);
C_ASSERT(FIELD_OFFSET(G49_TOUCH_RESULT,PostIrq)==27468);
