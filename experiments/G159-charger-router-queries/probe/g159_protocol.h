#ifndef G159_PROTOCOL_H
#define G159_PROTOCOL_H
#define G159_MAGIC 0x314c47393531474fULL /* OG159GL1 */
#define G159_ABI 1u
#define G159_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0xa60,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G159_IOCTL_READ CTL_CODE(FILE_DEVICE_UNKNOWN,0xa61,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define G159_IOCTL_RESULT CTL_CODE(FILE_DEVICE_UNKNOWN,0xa62,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct{ULONG Size,Version;ULONGLONG Magic,Nonce;ULONG Count,Reserved;}G159_REQUEST;
typedef struct{ULONG Size,Version;ULONGLONG Magic;ULONG KernelBuild,Processors,Irql,FirmwareBytes,FirmwareMatch,FirmwareStatus,MapCalls,Attempts,Ready,Fault;ULONGLONG InterruptTime,Frequency,Sequence;}G159_STATUS;
typedef struct {
 G159_STATUS Status;ULONGLONG Nonce,Begin,End;
 ULONG Code,MapCalls,FdtMatch,TocMatch,SlotsMatch,Cancelled,TimedOut,Reserved;
 UCHAR FdtDigest[32];G158_SLOTS Slots;G159_STATE State;
 uint32_t InitialDescriptor[8],FinalDescriptor[8];
 UCHAR Tx[G159_FIFO_BYTES],Rx[G159_FIFO_BYTES];
}G159_CAPTURE;
C_ASSERT(sizeof(G159_REQUEST)==32);C_ASSERT(sizeof(G159_STATUS)==80);
C_ASSERT(sizeof(G159_STATE)==48216);C_ASSERT(sizeof(G158_SLOTS)==20);
C_ASSERT(FIELD_OFFSET(G159_CAPTURE,State)==188);
C_ASSERT(FIELD_OFFSET(G159_CAPTURE,Tx)==48468);
C_ASSERT(FIELD_OFFSET(G159_CAPTURE,Rx)==64852);
C_ASSERT(sizeof(G159_CAPTURE)==81240);
#endif
