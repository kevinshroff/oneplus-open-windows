#ifndef G101_PROTOCOL_H
#define G101_PROTOCOL_H
#define G101_MAGIC 0x314452313031474fULL
#define G101_ABI 1u
#define G101_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0xa20,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G101_IOCTL_READ CTL_CODE(FILE_DEVICE_UNKNOWN,0xa21,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define G101_IOCTL_RESULT CTL_CODE(FILE_DEVICE_UNKNOWN,0xa22,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct{ULONG Size,Version;ULONGLONG Magic,Nonce;ULONG Count,Reserved;}G101_REQUEST;
typedef struct{ULONG Size,Version;ULONGLONG Magic;ULONG KernelBuild,Processors,Irql,FirmwareBytes,FirmwareMatch,FirmwareStatus,MapCalls,Attempts,Ready,Fault;ULONGLONG InterruptTime,Frequency,Sequence;}G101_STATUS;
typedef struct{G101_STATUS Status;ULONGLONG Nonce;ULONG NativeReads,MapCalls,Guard,Reserved;G101_RESULT Result;}G101_CAPTURE;
C_ASSERT(sizeof(G101_REQUEST)==32);C_ASSERT(sizeof(G101_STATUS)==80);
C_ASSERT(sizeof(G101_RESULT)==8600);C_ASSERT(FIELD_OFFSET(G101_CAPTURE,Result)==104);C_ASSERT(sizeof(G101_CAPTURE)==8704);
#endif
