#ifndef G50_PROTOCOL_H
#define G50_PROTOCOL_H
#define G50_ABI 1u
#define G50_MAGIC 0x314f52463035474fULL
#define G50_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G50_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G50_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G50_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G50_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G50_STATUS;
typedef struct {G50_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G50_REGISTER_COUNT];} G50_SNAPSHOT;
typedef struct {
 G50_STATUS Status;G50_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G50_PMIC;
typedef struct {
 G50_STATUS Status;G50_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G50_TRIAL;
C_ASSERT(sizeof(G50_REQUEST)==16);
C_ASSERT(sizeof(G50_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G50_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G50_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G50_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G50_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G50_PMIC)==1728);
C_ASSERT(sizeof(G50_RSC_RESULT)==3264);
C_ASSERT(sizeof(G50_POWER_RESULT)==34392);
C_ASSERT(sizeof(G50_TOUCH_RESULT)==27600);
C_ASSERT(sizeof(G50_TRIAL_RESULT)==69068);
C_ASSERT(FIELD_OFFSET(G50_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G50_TRIAL,ElapsedTicks)==69160);
C_ASSERT(sizeof(G50_TRIAL)==69176);
#endif

