#ifndef G34_PROTOCOL_H
#define G34_PROTOCOL_H
#define G34_ABI 1u
#define G34_MAGIC 0x314f52463433474fULL
#define G34_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G34_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G34_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G34_STATUS;
typedef struct {G34_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G34_REGISTER_COUNT];} G34_SNAPSHOT;
C_ASSERT(sizeof(G34_REQUEST)==16);
C_ASSERT(sizeof(G34_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G34_SNAPSHOT,Values)==88);
#endif
