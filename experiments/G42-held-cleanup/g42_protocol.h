#ifndef G42_PROTOCOL_H
#define G42_PROTOCOL_H
#define G42_ABI 1u
#define G42_MAGIC 0x314f52463234474fULL
#define G42_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G42_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G42_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G42_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G42_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G42_STATUS;
typedef struct {G42_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G42_REGISTER_COUNT];} G42_SNAPSHOT;
typedef struct {
 G42_STATUS Status;G42_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G42_PMIC;
typedef struct {
 G42_STATUS Status;G42_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G42_TRIAL;
C_ASSERT(sizeof(G42_REQUEST)==16);
C_ASSERT(sizeof(G42_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G42_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G42_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G42_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G42_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G42_PMIC)==1728);
C_ASSERT(sizeof(G42_RSC_RESULT)==3264);
C_ASSERT(sizeof(G42_POWER_RESULT)==34392);
C_ASSERT(sizeof(G42_TOUCH_RESULT)==14292);
C_ASSERT(sizeof(G42_TRIAL_RESULT)==55760);
C_ASSERT(FIELD_OFFSET(G42_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G42_TRIAL,ElapsedTicks)==55848);
C_ASSERT(sizeof(G42_TRIAL)==55864);
#endif
