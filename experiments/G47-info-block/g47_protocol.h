#ifndef G47_PROTOCOL_H
#define G47_PROTOCOL_H
#define G47_ABI 1u
#define G47_MAGIC 0x314f52463734474fULL
#define G47_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G47_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G47_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G47_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G47_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G47_STATUS;
typedef struct {G47_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G47_REGISTER_COUNT];} G47_SNAPSHOT;
typedef struct {
 G47_STATUS Status;G47_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G47_PMIC;
typedef struct {
 G47_STATUS Status;G47_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G47_TRIAL;
C_ASSERT(sizeof(G47_REQUEST)==16);
C_ASSERT(sizeof(G47_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G47_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G47_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G47_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G47_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G47_PMIC)==1728);
C_ASSERT(sizeof(G47_RSC_RESULT)==3264);
C_ASSERT(sizeof(G47_POWER_RESULT)==34392);
C_ASSERT(sizeof(G47_TOUCH_RESULT)==27024);
C_ASSERT(sizeof(G47_TRIAL_RESULT)==68492);
C_ASSERT(FIELD_OFFSET(G47_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G47_TRIAL,ElapsedTicks)==68584);
C_ASSERT(sizeof(G47_TRIAL)==68600);
#endif
