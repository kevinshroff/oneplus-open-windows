#ifndef G158_PROTOCOL_H
#define G158_PROTOCOL_H
#define G158_MAGIC 0x314c47383531474fULL /* OG158GL1 */
#define G158_ABI 1u
#define G158_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0xa50,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G158_IOCTL_READ CTL_CODE(FILE_DEVICE_UNKNOWN,0xa51,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define G158_IOCTL_RESULT CTL_CODE(FILE_DEVICE_UNKNOWN,0xa52,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct{ULONG Size,Version;ULONGLONG Magic,Nonce;ULONG Count,Reserved;}G158_REQUEST;
typedef struct{ULONG Size,Version;ULONGLONG Magic;ULONG KernelBuild,Processors,Irql,FirmwareBytes,FirmwareMatch,FirmwareStatus,MapCalls,Attempts,Ready,Fault;ULONGLONG InterruptTime,Frequency,Sequence;}G158_STATUS;
typedef struct {
 G158_STATUS Status;ULONGLONG Nonce,Begin,End;
 ULONG Code,MapCalls,FdtMatch,TocMatch,SlotsMatch,Cancelled,TimedOut,Reserved;
 UCHAR FdtDigest[32];G158_SLOTS Slots;G158_STATE State;
 uint32_t InitialDescriptor[8],FinalDescriptor[8];
 UCHAR Tx[G158_FIFO_BYTES],Rx[G158_FIFO_BYTES];
}G158_CAPTURE;
C_ASSERT(sizeof(G158_REQUEST)==32);C_ASSERT(sizeof(G158_STATUS)==80);
C_ASSERT(sizeof(G158_STATE)==1128);C_ASSERT(sizeof(G158_SLOTS)==20);
C_ASSERT(FIELD_OFFSET(G158_CAPTURE,State)==188);
C_ASSERT(FIELD_OFFSET(G158_CAPTURE,Tx)==1380);
C_ASSERT(FIELD_OFFSET(G158_CAPTURE,Rx)==17764);
C_ASSERT(sizeof(G158_CAPTURE)==34152);
#endif
