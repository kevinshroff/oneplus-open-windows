#ifndef G38_PROTOCOL_H
#define G38_PROTOCOL_H
#define G38_ABI 1u
#define G38_MAGIC 0x314f52463833474fULL
#define G38_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G38_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G38_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G38_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G38_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G38_STATUS;
typedef struct {G38_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G38_REGISTER_COUNT];} G38_SNAPSHOT;
typedef struct {
 G38_STATUS Status;G38_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G38_PMIC;
typedef struct {
 G38_STATUS Status;G38_POWER_RESULT Power;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G38_POWER;
C_ASSERT(sizeof(G38_REQUEST)==16);
C_ASSERT(sizeof(G38_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G38_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G38_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G38_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G38_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G38_PMIC)==1728);
C_ASSERT(sizeof(G38_RSC_RESULT)==3264);
C_ASSERT(sizeof(G38_POWER_RESULT)==34392);
C_ASSERT(FIELD_OFFSET(G38_POWER,Power)==80);
C_ASSERT(FIELD_OFFSET(G38_POWER,ElapsedTicks)==34480);
C_ASSERT(sizeof(G38_POWER)==34496);
#endif
