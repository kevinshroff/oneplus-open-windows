#ifndef G43_PROTOCOL_H
#define G43_PROTOCOL_H
#define G43_ABI 1u
#define G43_MAGIC 0x314f52463334474fULL
#define G43_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G43_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G43_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G43_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G43_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G43_STATUS;
typedef struct {G43_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G43_REGISTER_COUNT];} G43_SNAPSHOT;
typedef struct {
 G43_STATUS Status;G43_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G43_PMIC;
typedef struct {
 G43_STATUS Status;G43_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G43_TRIAL;
C_ASSERT(sizeof(G43_REQUEST)==16);
C_ASSERT(sizeof(G43_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G43_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G43_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G43_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G43_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G43_PMIC)==1728);
C_ASSERT(sizeof(G43_RSC_RESULT)==3264);
C_ASSERT(sizeof(G43_POWER_RESULT)==34392);
C_ASSERT(sizeof(G43_TOUCH_RESULT)==14292);
C_ASSERT(sizeof(G43_TRIAL_RESULT)==55760);
C_ASSERT(FIELD_OFFSET(G43_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G43_TRIAL,ElapsedTicks)==55848);
C_ASSERT(sizeof(G43_TRIAL)==55864);
#endif
