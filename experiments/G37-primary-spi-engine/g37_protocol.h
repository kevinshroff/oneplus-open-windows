#ifndef G37_PROTOCOL_H
#define G37_PROTOCOL_H
#define G37_ABI 1u
#define G37_MAGIC 0x314f52463733474fULL
#define G37_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G37_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G37_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G37_IOCTL_SPI CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G37_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G37_STATUS;
typedef struct {G37_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G37_REGISTER_COUNT];} G37_SNAPSHOT;
typedef struct {
 G37_STATUS Status;G37_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G37_PMIC;
typedef struct {
 G37_STATUS Status;G37_SPI_RESULT Spi;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G37_SPI;
C_ASSERT(sizeof(G37_REQUEST)==16);
C_ASSERT(sizeof(G37_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G37_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G37_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G37_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G37_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G37_PMIC)==1728);
C_ASSERT(sizeof(G37_ENGINE_RESULT)==5220);
C_ASSERT(FIELD_OFFSET(G37_SPI_RESULT,Engine)==1848);
C_ASSERT(sizeof(G37_SPI_RESULT)==7068);
C_ASSERT(FIELD_OFFSET(G37_SPI,Spi)==80);
C_ASSERT(FIELD_OFFSET(G37_SPI,ElapsedTicks)==7160);
C_ASSERT(sizeof(G37_SPI)==7176);
#endif
