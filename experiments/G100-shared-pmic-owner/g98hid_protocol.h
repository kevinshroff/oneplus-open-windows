#ifndef OPEN_G98HID_PROTOCOL_H
#define OPEN_G98HID_PROTOCOL_H
#define G98HID_MAGIC 0x314448383947504fULL
#define G98HID_ABI 1u
#define G98HID_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x900,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G98HID_IOCTL_SESSION CTL_CODE(FILE_DEVICE_UNKNOWN,0x901,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G98HID_IOCTL_START CTL_CODE(FILE_DEVICE_UNKNOWN,0x902,METHOD_BUFFERED,FILE_WRITE_ACCESS)
#define G98HID_IOCTL_PLAY CTL_CODE(FILE_DEVICE_UNKNOWN,0x904,METHOD_BUFFERED,FILE_WRITE_ACCESS)
#define G98HID_IOCTL_STOP CTL_CODE(FILE_DEVICE_UNKNOWN,0x903,METHOD_BUFFERED,FILE_WRITE_ACCESS)
#define G98HID_IOCTL_RUNTIME CTL_CODE(FILE_DEVICE_UNKNOWN,0x905,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G98HID_IOCTL_RUN CTL_CODE(FILE_DEVICE_UNKNOWN,0x906,METHOD_BUFFERED,FILE_WRITE_ACCESS)
#define G98HID_IOCTL_FAULT CTL_CODE(FILE_DEVICE_UNKNOWN,0x907,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size,Version;ULONGLONG Magic;ULONG Present,PollCode,FrameError,ReadBytes;ULONGLONG AtUs;UCHAR Bytes[90],Padding[6];}G98_FAULT;
C_ASSERT(sizeof(G98_FAULT)==136);
enum {G98_OWNER_IDLE=0,G98_OWNER_QUEUED=1,G98_OWNER_RUNNING=2,G98_OWNER_DONE=3};
enum {G98_OUTCOME_NONE=0,G98_OUTCOME_COMPLETE=1,G98_OUTCOME_CANCELLED=2,G98_OUTCOME_FAILED=3,G98_OUTCOME_CANCELLED_BEFORE_HARDWARE=4};
enum {G98_STOP_NONE=0,G98_STOP_EXPLICIT=1,G98_STOP_CLOSE=2,G98_STOP_SUSPEND=3,G98_STOP_D0_EXIT=4,G98_STOP_CLEANUP=5,G98_STOP_SURPRISE=6};
typedef struct {
 ULONG Size,Version;ULONGLONG Magic;
 ULONG State,StopReason,Starts,HardwareCalls,ResultReady,Outcome,StopChecks,StopSeen,Inhibit,ThreadJoined,Phase,PollCycles;
 ULONGLONG BeginUs,EndUs,StopUs;ULONG ThreadCreateStatus,StopRequests;
}G98_SESSION;
C_ASSERT(sizeof(G98_SESSION)==96);
C_ASSERT(FIELD_OFFSET(G98_SESSION,BeginUs)==64);
typedef struct {
 ULONG Size,Version;ULONGLONG Magic;
 ULONG State,StopReason,Starts,HardwareCalls,ResultReady,Outcome,Inhibit,ThreadJoined;
 ULONGLONG Cycles,Epochs,ReportsSubmitted,ReportsAccepted,Reads,Writes,Wires,BeginUs,LastCycleUs,OwnerStarts,Recoveries;
 ULONG HardwareCode,PollCode,TouchCode,D0,Started,FaultReady;
}G98_RUNTIME;
C_ASSERT(sizeof(G98_RUNTIME)==160);
static const GUID G98HIDInterface={0x5f9cc9b9,0xb53a,0x4ec2,{0xa8,0x79,0xb5,0x8e,0xfe,0xdf,0x00,0x98}};
typedef struct {ULONG Size,Version;ULONGLONG Magic;} G98HID_REQUEST;
typedef struct {
 ULONG Size,Version;ULONGLONG Magic;
 ULONG KernelBuild,Processors,Irql,FirmwareBytes,FirmwareMatch,D0,Started,CreateStatus,StartStatus,Entries,Exits,Features,LiveAttempts,ReportsAccepted,LastSubmit,MaxContacts,MaxX,MaxY,ReportBytes,DescriptorBytes,MappingQualified;
 ULONGLONG Sequence;UCHAR BuildId[16];
 ULONG LiveComplete,LiveError,StopAttempts,StopAccepted,AcceptedMask,AcceptedGeneration,ReportsSubmitted,Reserved;
} G98HID_STATUS;
C_ASSERT(sizeof(G98HID_REQUEST)==16);
C_ASSERT(sizeof(G98HID_STATUS)==160);
C_ASSERT(FIELD_OFFSET(G98HID_STATUS,Sequence)==104);
C_ASSERT(FIELD_OFFSET(G98HID_STATUS,BuildId)==112);
#endif
