#ifndef G102_PROTOCOL_H
#define G102_PROTOCOL_H
#define G102_MAGIC 0x314452323031474fULL
#define G102_ABI 1u
#define G102_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0xa20,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G102_IOCTL_READ CTL_CODE(FILE_DEVICE_UNKNOWN,0xa21,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define G102_IOCTL_RESULT CTL_CODE(FILE_DEVICE_UNKNOWN,0xa22,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct{ULONG Size,Version;ULONGLONG Magic,Nonce;ULONG Count,Reserved;}G102_REQUEST;
typedef struct{ULONG Size,Version;ULONGLONG Magic;ULONG KernelBuild,Processors,Irql,FirmwareBytes,FirmwareMatch,FirmwareStatus,MapCalls,Attempts,Ready,Fault;ULONGLONG InterruptTime,Frequency,Sequence;}G102_STATUS;
typedef struct{G102_STATUS Status;ULONGLONG Nonce;ULONG NativeReads,MapCalls,Guard,Reserved;G102_RESULT Result;}G102_CAPTURE;
C_ASSERT(sizeof(G102_REQUEST)==32);C_ASSERT(sizeof(G102_STATUS)==80);
C_ASSERT(sizeof(G102_RESULT)==8728);C_ASSERT(FIELD_OFFSET(G102_CAPTURE,Result)==104);C_ASSERT(sizeof(G102_CAPTURE)==8832);
#endif
