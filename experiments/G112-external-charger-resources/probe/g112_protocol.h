#ifndef G112_PROTOCOL_H
#define G112_PROTOCOL_H
#define G112_MAGIC 0x314452323131474fULL
#define G112_ABI 1u
#define G112_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0xa20,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G112_IOCTL_READ CTL_CODE(FILE_DEVICE_UNKNOWN,0xa21,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define G112_IOCTL_RESULT CTL_CODE(FILE_DEVICE_UNKNOWN,0xa22,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct{ULONG Size,Version;ULONGLONG Magic,Nonce;ULONG Count,Reserved;}G112_REQUEST;
typedef struct{ULONG Size,Version;ULONGLONG Magic;ULONG KernelBuild,Processors,Irql,FirmwareBytes,FirmwareMatch,FirmwareStatus,MapCalls,Attempts,Ready,Fault;ULONGLONG InterruptTime,Frequency,Sequence;}G112_STATUS;
typedef struct{G112_STATUS Status;ULONGLONG Nonce;ULONG NativeReads,MapCalls,Guard,Reserved;G112_RESULT Result;}G112_CAPTURE;
C_ASSERT(sizeof(G112_REQUEST)==32);C_ASSERT(sizeof(G112_STATUS)==80);
C_ASSERT(sizeof(G112_RESULT)==8600);C_ASSERT(FIELD_OFFSET(G112_CAPTURE,Result)==104);C_ASSERT(sizeof(G112_CAPTURE)==8704);
#endif
