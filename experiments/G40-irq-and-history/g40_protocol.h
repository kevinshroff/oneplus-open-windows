#ifndef G40_PROTOCOL_H
#define G40_PROTOCOL_H
#define G40_ABI 1u
#define G40_MAGIC 0x314f52463034474fULL
#define G40_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G40_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G40_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G40_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G40_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G40_STATUS;
typedef struct {G40_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G40_REGISTER_COUNT];} G40_SNAPSHOT;
typedef struct {
 G40_STATUS Status;G40_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G40_PMIC;
typedef struct {
 G40_STATUS Status;G40_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G40_TRIAL;
C_ASSERT(sizeof(G40_REQUEST)==16);
C_ASSERT(sizeof(G40_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G40_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G40_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G40_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G40_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G40_PMIC)==1728);
C_ASSERT(sizeof(G40_RSC_RESULT)==3264);
C_ASSERT(sizeof(G40_POWER_RESULT)==34392);
C_ASSERT(sizeof(G40_TOUCH_RESULT)==14292);
C_ASSERT(sizeof(G40_TRIAL_RESULT)==55760);
C_ASSERT(FIELD_OFFSET(G40_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G40_TRIAL,ElapsedTicks)==55848);
C_ASSERT(sizeof(G40_TRIAL)==55864);
#endif
