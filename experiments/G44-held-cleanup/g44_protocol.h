#ifndef G44_PROTOCOL_H
#define G44_PROTOCOL_H
#define G44_ABI 1u
#define G44_MAGIC 0x314f52463434474fULL
#define G44_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G44_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G44_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G44_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G44_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G44_STATUS;
typedef struct {G44_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G44_REGISTER_COUNT];} G44_SNAPSHOT;
typedef struct {
 G44_STATUS Status;G44_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G44_PMIC;
typedef struct {
 G44_STATUS Status;G44_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G44_TRIAL;
C_ASSERT(sizeof(G44_REQUEST)==16);
C_ASSERT(sizeof(G44_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G44_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G44_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G44_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G44_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G44_PMIC)==1728);
C_ASSERT(sizeof(G44_RSC_RESULT)==3264);
C_ASSERT(sizeof(G44_POWER_RESULT)==34392);
C_ASSERT(sizeof(G44_TOUCH_RESULT)==14292);
C_ASSERT(sizeof(G44_TRIAL_RESULT)==55760);
C_ASSERT(FIELD_OFFSET(G44_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G44_TRIAL,ElapsedTicks)==55848);
C_ASSERT(sizeof(G44_TRIAL)==55864);
#endif
