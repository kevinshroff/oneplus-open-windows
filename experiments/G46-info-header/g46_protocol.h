#ifndef G46_PROTOCOL_H
#define G46_PROTOCOL_H
#define G46_ABI 1u
#define G46_MAGIC 0x314f52463634474fULL
#define G46_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G46_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G46_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G46_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G46_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G46_STATUS;
typedef struct {G46_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G46_REGISTER_COUNT];} G46_SNAPSHOT;
typedef struct {
 G46_STATUS Status;G46_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G46_PMIC;
typedef struct {
 G46_STATUS Status;G46_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G46_TRIAL;
C_ASSERT(sizeof(G46_REQUEST)==16);
C_ASSERT(sizeof(G46_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G46_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G46_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G46_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G46_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G46_PMIC)==1728);
C_ASSERT(sizeof(G46_RSC_RESULT)==3264);
C_ASSERT(sizeof(G46_POWER_RESULT)==34392);
C_ASSERT(sizeof(G46_TOUCH_RESULT)==14300);
C_ASSERT(sizeof(G46_TRIAL_RESULT)==55768);
C_ASSERT(FIELD_OFFSET(G46_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G46_TRIAL,ElapsedTicks)==55856);
C_ASSERT(sizeof(G46_TRIAL)==55872);
#endif
