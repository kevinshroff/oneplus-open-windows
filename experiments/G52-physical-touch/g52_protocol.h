#ifndef G52_PROTOCOL_H
#define G52_PROTOCOL_H
#define G52_ABI 1u
#define G52_MAGIC 0x314f52463235474fULL
#define G52_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G52_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G52_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G52_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G52_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G52_STATUS;
typedef struct {G52_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G52_REGISTER_COUNT];} G52_SNAPSHOT;
typedef struct {
 G52_STATUS Status;G52_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G52_PMIC;
typedef struct {
 G52_STATUS Status;G52_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G52_TRIAL;
C_ASSERT(sizeof(G52_REQUEST)==16);
C_ASSERT(sizeof(G52_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G52_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G52_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G52_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G52_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G52_PMIC)==1728);
C_ASSERT(sizeof(G52_RSC_RESULT)==3264);
C_ASSERT(sizeof(G52_POWER_RESULT)==34392);
C_ASSERT(sizeof(G52_TOUCH_RESULT)==27600);
C_ASSERT(sizeof(G52_TRIAL_RESULT)==69068);
C_ASSERT(FIELD_OFFSET(G52_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G52_TRIAL,ElapsedTicks)==69160);
C_ASSERT(sizeof(G52_TRIAL)==69176);
#endif

