static int G110Gate(const unsigned*clock0,const unsigned*core,const unsigned*clock1,const unsigned*int2)
{
 /* Conservative: require both domains fully up, no collapse/reset, and all
  * three branch enables set with CLK_OFF clear. Do not enable anything. */
 return !(clock0[0]&1)&&!(clock1[0]&1)&&
  (clock0[1]&0x80000001u)==1&&(clock0[2]&0x80000001u)==1&&
  (clock1[1]&0x80000001u)==1&&
  (core[0]&0x80000001u)==0x80000000u&&(int2[0]&0x80000001u)==0x80000000u&&
  (core[1]&0x18000u)==0x10000u&&(int2[1]&0x18000u)==0x10000u;
}
