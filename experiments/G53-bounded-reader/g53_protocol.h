#ifndef G53_PROTOCOL_H
#define G53_PROTOCOL_H
#define G53_ABI 1u
#define G53_MAGIC 0x314f52463335474fULL
#define G53_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G53_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G53_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G53_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G53_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G53_STATUS;
typedef struct {G53_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G53_REGISTER_COUNT];} G53_SNAPSHOT;
typedef struct {
 G53_STATUS Status;G53_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G53_PMIC;
typedef struct {
 G53_STATUS Status;G53_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G53_TRIAL;
C_ASSERT(sizeof(G53_REQUEST)==16);
C_ASSERT(sizeof(G53_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G53_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G53_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G53_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G53_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G53_PMIC)==1728);
C_ASSERT(sizeof(G53_RSC_RESULT)==3264);
C_ASSERT(sizeof(G53_POWER_RESULT)==34392);
C_ASSERT(sizeof(G53_TOUCH_RESULT)==109312);
C_ASSERT(sizeof(G53_TRIAL_RESULT)==150780);
C_ASSERT(FIELD_OFFSET(G53_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G53_TRIAL,ElapsedTicks)==150872);
C_ASSERT(sizeof(G53_TRIAL)==150888);
#endif

