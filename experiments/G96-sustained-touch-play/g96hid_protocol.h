#ifndef OPEN_G96HID_PROTOCOL_H
#define OPEN_G96HID_PROTOCOL_H
#define G96HID_MAGIC 0x314448363947504fULL
#define G96HID_ABI 1u
#define G96HID_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x900,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G96HID_IOCTL_SESSION CTL_CODE(FILE_DEVICE_UNKNOWN,0x901,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G96HID_IOCTL_START CTL_CODE(FILE_DEVICE_UNKNOWN,0x902,METHOD_BUFFERED,FILE_WRITE_ACCESS)
#define G96HID_IOCTL_PLAY CTL_CODE(FILE_DEVICE_UNKNOWN,0x904,METHOD_BUFFERED,FILE_WRITE_ACCESS)
#define G96HID_IOCTL_STOP CTL_CODE(FILE_DEVICE_UNKNOWN,0x903,METHOD_BUFFERED,FILE_WRITE_ACCESS)
enum {G96_OWNER_IDLE=0,G96_OWNER_QUEUED=1,G96_OWNER_RUNNING=2,G96_OWNER_DONE=3};
enum {G96_OUTCOME_NONE=0,G96_OUTCOME_COMPLETE=1,G96_OUTCOME_CANCELLED=2,G96_OUTCOME_FAILED=3,G96_OUTCOME_CANCELLED_BEFORE_HARDWARE=4};
enum {G96_STOP_NONE=0,G96_STOP_EXPLICIT=1,G96_STOP_CLOSE=2,G96_STOP_SUSPEND=3,G96_STOP_D0_EXIT=4,G96_STOP_CLEANUP=5,G96_STOP_SURPRISE=6};
typedef struct {
 ULONG Size,Version;ULONGLONG Magic;
 ULONG State,StopReason,Starts,HardwareCalls,ResultReady,Outcome,StopChecks,StopSeen,Inhibit,ThreadJoined,Phase,PollCycles;
 ULONGLONG BeginUs,EndUs,StopUs;ULONG ThreadCreateStatus,StopRequests;
}G96_SESSION;
C_ASSERT(sizeof(G96_SESSION)==96);
C_ASSERT(FIELD_OFFSET(G96_SESSION,BeginUs)==64);
static const GUID G96HIDInterface={0x5f9cc9b9,0xb53a,0x4ec2,{0xa8,0x79,0xb5,0x8e,0xfe,0xdf,0x00,0x96}};
typedef struct {ULONG Size,Version;ULONGLONG Magic;} G96HID_REQUEST;
typedef struct {
 ULONG Size,Version;ULONGLONG Magic;
 ULONG KernelBuild,Processors,Irql,FirmwareBytes,FirmwareMatch,D0,Started,CreateStatus,StartStatus,Entries,Exits,Features,LiveAttempts,ReportsAccepted,LastSubmit,MaxContacts,MaxX,MaxY,ReportBytes,DescriptorBytes,MappingQualified;
 ULONGLONG Sequence;UCHAR BuildId[16];
 ULONG LiveComplete,LiveError,StopAttempts,StopAccepted,AcceptedMask,AcceptedGeneration,ReportsSubmitted,Reserved;
} G96HID_STATUS;
C_ASSERT(sizeof(G96HID_REQUEST)==16);
C_ASSERT(sizeof(G96HID_STATUS)==160);
C_ASSERT(FIELD_OFFSET(G96HID_STATUS,Sequence)==104);
C_ASSERT(FIELD_OFFSET(G96HID_STATUS,BuildId)==112);
#endif
