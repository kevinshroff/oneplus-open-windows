#ifndef G41_PROTOCOL_H
#define G41_PROTOCOL_H
#define G41_ABI 1u
#define G41_MAGIC 0x314f52463134474fULL
#define G41_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G41_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G41_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G41_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G41_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G41_STATUS;
typedef struct {G41_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G41_REGISTER_COUNT];} G41_SNAPSHOT;
typedef struct {
 G41_STATUS Status;G41_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G41_PMIC;
typedef struct {
 G41_STATUS Status;G41_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G41_TRIAL;
C_ASSERT(sizeof(G41_REQUEST)==16);
C_ASSERT(sizeof(G41_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G41_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G41_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G41_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G41_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G41_PMIC)==1728);
C_ASSERT(sizeof(G41_RSC_RESULT)==3264);
C_ASSERT(sizeof(G41_POWER_RESULT)==34392);
C_ASSERT(sizeof(G41_TOUCH_RESULT)==14292);
C_ASSERT(sizeof(G41_TRIAL_RESULT)==55760);
C_ASSERT(FIELD_OFFSET(G41_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G41_TRIAL,ElapsedTicks)==55848);
C_ASSERT(sizeof(G41_TRIAL)==55864);
#endif
