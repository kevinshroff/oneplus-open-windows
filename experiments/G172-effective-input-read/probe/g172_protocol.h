#ifndef G172_PROTOCOL_H
#define G172_PROTOCOL_H
#include "g111_core.h"
#define G172_MAGIC 0x314d50323731474fULL
#define G172_ABI 1u
#define G172_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0xa80,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G172_IOCTL_READ CTL_CODE(FILE_DEVICE_UNKNOWN,0xa81,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define G172_IOCTL_RESULT CTL_CODE(FILE_DEVICE_UNKNOWN,0xa82,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct{ULONG Size,Version;ULONGLONG Magic,Nonce;ULONG Count,Reserved;}G172_REQUEST;
typedef struct{ULONG Size,Version;ULONGLONG Magic;ULONG KernelBuild,Processors,Irql,FirmwareBytes,FirmwareMatch,FirmwareStatus,MapCalls,Attempts,Ready,Fault;ULONGLONG InterruptTime,Frequency,Sequence;}G172_STATUS;
typedef struct{G172_STATUS Status;ULONGLONG Nonce;ULONG NativeReads,NativeWrites,NativeGuard,Reserved;ULONGLONG Begin,End;G111_RESULT Result;}G172_CAPTURE;
C_ASSERT(sizeof(G172_REQUEST)==32);C_ASSERT(sizeof(G172_STATUS)==80);C_ASSERT(sizeof(G111_RESULT)==592);
C_ASSERT(FIELD_OFFSET(G172_CAPTURE,Result)==120);C_ASSERT(sizeof(G172_CAPTURE)==712);
#endif

C_ASSERT(FIELD_OFFSET(G111_RESULT,Values)==64);
C_ASSERT(FIELD_OFFSET(G111_RESULT,Trace)==152);
C_ASSERT(FIELD_OFFSET(G172_CAPTURE,Begin)==104);
C_ASSERT(FIELD_OFFSET(G172_CAPTURE,End)==112);
