#ifndef G35_PROTOCOL_H
#define G35_PROTOCOL_H
#define G35_ABI 1u
#define G35_MAGIC 0x314f52463533474fULL
#define G35_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G35_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G35_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G35_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G35_STATUS;
typedef struct {G35_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G35_REGISTER_COUNT];} G35_SNAPSHOT;
typedef struct {
 G35_STATUS Status;G35_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G35_PMIC;
C_ASSERT(sizeof(G35_REQUEST)==16);
C_ASSERT(sizeof(G35_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G35_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G35_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G35_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G35_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G35_PMIC)==1728);
#endif
