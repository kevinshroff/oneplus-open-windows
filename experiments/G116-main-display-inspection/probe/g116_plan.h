static int G116Gate(const unsigned*clock0,const unsigned*core)
{
 /* Main/common domain only. Source binds MDSS and its MDP child to main
  * GDSC. The second island is observed, never enabled or used for admission.
  * Refuse HW-trigger mode, SW override and software collapse. Both main
  * branch requests must be asserted, CLK_OFF clear, and reset deasserted.
  * This is a finite passive query, not a production power-management lease. */
 return !(clock0[0]&1u)&&
  (clock0[1]&0x80000001u)==1u&&(clock0[2]&0x80000001u)==1u&&
  (core[0]&0x80000007u)==0x80000000u&&
  (core[1]&0x18000u)==0x10000u;
}
