#ifndef G36_PROTOCOL_H
#define G36_PROTOCOL_H
#define G36_ABI 1u
#define G36_MAGIC 0x314f52463633474fULL
#define G36_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G36_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G36_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G36_IOCTL_SPI CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G36_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G36_STATUS;
typedef struct {G36_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G36_REGISTER_COUNT];} G36_SNAPSHOT;
typedef struct {
 G36_STATUS Status;G36_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G36_PMIC;
typedef struct {
 G36_STATUS Status;G36_SPI_RESULT Spi;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G36_SPI;
C_ASSERT(sizeof(G36_REQUEST)==16);
C_ASSERT(sizeof(G36_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G36_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G36_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G36_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G36_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G36_PMIC)==1728);
C_ASSERT(sizeof(G36_SPI_RESULT)==1848);
C_ASSERT(FIELD_OFFSET(G36_SPI,Spi)==80);
C_ASSERT(FIELD_OFFSET(G36_SPI,ElapsedTicks)==1936);
C_ASSERT(sizeof(G36_SPI)==1952);
#endif
