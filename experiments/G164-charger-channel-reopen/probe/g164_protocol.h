#ifndef G164_PROTOCOL_H
#define G164_PROTOCOL_H
#define G164_MAGIC 0x314c47343631474fULL /* OG164GL1 */
#define G164_ABI 1u
#define G164_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0xa90,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G164_IOCTL_READ CTL_CODE(FILE_DEVICE_UNKNOWN,0xa91,METHOD_BUFFERED,FILE_READ_ACCESS|FILE_WRITE_ACCESS)
#define G164_IOCTL_RESULT CTL_CODE(FILE_DEVICE_UNKNOWN,0xa92,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct{ULONG Size,Version;ULONGLONG Magic,Nonce;ULONG Count,Reserved;}G164_REQUEST;
typedef struct{ULONG Size,Version;ULONGLONG Magic;ULONG KernelBuild,Processors,Irql,FirmwareBytes,FirmwareMatch,FirmwareStatus,MapCalls,Attempts,Ready,Fault;ULONGLONG InterruptTime,Frequency,Sequence;}G164_STATUS;
typedef struct {
 G164_STATUS Status;ULONGLONG Nonce,Begin,End;
 ULONG Code,MapCalls,FdtMatch,TocMatch,SlotsMatch,Cancelled,TimedOut,Reserved;
 UCHAR FdtDigest[32];G158_SLOTS Slots;G164_STATE State;
 uint32_t InitialDescriptor[8],FinalDescriptor[8];
 UCHAR Tx[G164_FIFO_BYTES],Rx[G164_FIFO_BYTES];
}G164_CAPTURE;
C_ASSERT(sizeof(G164_REQUEST)==32);C_ASSERT(sizeof(G164_STATUS)==80);
C_ASSERT(sizeof(G164_STATE)==48220);C_ASSERT(sizeof(G158_SLOTS)==20);
C_ASSERT(FIELD_OFFSET(G164_CAPTURE,State)==188);
C_ASSERT(FIELD_OFFSET(G164_CAPTURE,Tx)==48472);
C_ASSERT(FIELD_OFFSET(G164_CAPTURE,Rx)==64856);
C_ASSERT(sizeof(G164_CAPTURE)==81240);
#endif
