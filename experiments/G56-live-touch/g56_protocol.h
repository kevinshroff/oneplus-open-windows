C_ASSERT(FIELD_OFFSET(G56_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G56_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G56_PMIC)==1728);
C_ASSERT(sizeof(G56_RSC_RESULT)==3264);
C_ASSERT(sizeof(G56_POWER_RESULT)==34392);
C_ASSERT(sizeof(G56_TOUCH_RESULT)==888708);
C_ASSERT(sizeof(G56_TRIAL_RESULT)==930176);
C_ASSERT(FIELD_OFFSET(G56_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G56_TRIAL,ElapsedTicks)==930264);
C_ASSERT(sizeof(G56_TRIAL)==930280);
#endif

