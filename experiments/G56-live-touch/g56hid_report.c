void G56HIDEmptyReport(uint8_t*out,uint16_t scan)
{
 uint32_t i;for(i=0;i<G56HID_REPORT_BYTES;i++)out[i]=0;out[0]=1;
 for(i=0;i<G56HID_CONTACTS;i++)out[2+i*6]=(uint8_t)i;
 out[61]=(uint8_t)scan;out[62]=(uint8_t)(scan>>8);
}
int G56HIDIsEmptyReport(const uint8_t*p,uint32_t n)
{
 uint32_t i;if(!p||n!=G56HID_REPORT_BYTES||p[0]!=1||p[63]!=0)return 0;
 for(i=0;i<G56HID_CONTACTS;i++)if(p[1+i*6]||p[2+i*6]!=i||p[3+i*6]||p[4+i*6]||p[5+i*6]||p[6+i*6])return 0;
 return 1;
}
