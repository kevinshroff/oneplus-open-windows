#ifndef G48_PROTOCOL_H
#define G48_PROTOCOL_H
#define G48_ABI 1u
#define G48_MAGIC 0x314f52463834474fULL
#define G48_IOCTL_STATUS CTL_CODE(FILE_DEVICE_UNKNOWN,0x800,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G48_IOCTL_SNAPSHOT CTL_CODE(FILE_DEVICE_UNKNOWN,0x801,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G48_IOCTL_PMIC CTL_CODE(FILE_DEVICE_UNKNOWN,0x802,METHOD_BUFFERED,FILE_READ_ACCESS)
#define G48_IOCTL_POWER CTL_CODE(FILE_DEVICE_UNKNOWN,0x803,METHOD_BUFFERED,FILE_READ_ACCESS)
typedef struct {ULONG Size;ULONG Version;ULONGLONG Magic;} G48_REQUEST;
typedef struct {
 ULONG Size;ULONG Version;ULONGLONG Magic;
 ULONG KernelBuild;ULONG Processors;ULONG CurrentIrql;ULONG FirmwareBytes;
 ULONG FirmwareMatch;ULONG RegisterCount;ULONG FirmwareStatus;ULONG MapCalls;
 ULONGLONG Sequence;ULONGLONG InterruptTime;
 UCHAR BuildId[16];
} G48_STATUS;
typedef struct {G48_STATUS Status;ULONG Count;ULONG Reserved;ULONG Values[G48_REGISTER_COUNT];} G48_SNAPSHOT;
typedef struct {
 G48_STATUS Status;G48_OBS_RESULT Observer;
 ULONG FixedRegistersUnchanged;ULONG Attempt;ULONG Reserved;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G48_PMIC;
typedef struct {
 G48_STATUS Status;G48_TRIAL_RESULT Trial;
 ULONG FixedRegistersUnchanged;ULONG Attempt;
 ULONGLONG ElapsedTicks;ULONGLONG CounterFrequency;
} G48_TRIAL;
C_ASSERT(sizeof(G48_REQUEST)==16);
C_ASSERT(sizeof(G48_STATUS)==80);
C_ASSERT(FIELD_OFFSET(G48_SNAPSHOT,Values)==88);
C_ASSERT(sizeof(G48_OBS_RESULT)==1620);
C_ASSERT(FIELD_OFFSET(G48_PMIC,Observer)==80);
C_ASSERT(FIELD_OFFSET(G48_PMIC,ElapsedTicks)==1712);
C_ASSERT(sizeof(G48_PMIC)==1728);
C_ASSERT(sizeof(G48_RSC_RESULT)==3264);
C_ASSERT(sizeof(G48_POWER_RESULT)==34392);
C_ASSERT(sizeof(G48_TOUCH_RESULT)==27168);
C_ASSERT(sizeof(G48_TRIAL_RESULT)==68636);
C_ASSERT(FIELD_OFFSET(G48_TRIAL,Trial)==80);
C_ASSERT(FIELD_OFFSET(G48_TRIAL,ElapsedTicks)==68728);
C_ASSERT(sizeof(G48_TRIAL)==68744);
#endif
